CREATE TABLE `ROLE` (
  `ID` INT (50) NOT NULL COMMENT 'ID' AUTO_INCREMENT,
  `CD` VARCHAR (255) NOT NULL COMMENT 'コード',
  `NAME` VARCHAR (255) NOT NULL COMMENT '名称',
  `REMARKS` VARCHAR (255) DEFAULT NULL COMMENT '備考',
  `DELETE_FLG` CHAR (1) NOT NULL DEFAULT '0' COMMENT '削除フラグ',
  `VERSION` INT (50) DEFAULT '0' COMMENT 'バージョン',
  `CREATED` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '登録日時',
  `MODIFIED` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新日時',
  `MODIFIED_BY` VARCHAR (255) COMMENT '更新者',
  PRIMARY KEY(ID)
)
COMMENT='権限';
CREATE TABLE `STAFF_USER` (
