  `MODIFIED` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新日時',
  `MODIFIED_BY` VARCHAR (255) COMMENT '更新者',
  PRIMARY KEY(ID,GENRE_CODE)
